"""tools/pages/build.py: EldenNet's space, from its one source to what eldennet.dll registers (PAGES §2; GraceUI's
D160 and eldennet-changes §19 item 3).

    python3 -I tools/pages/build.py           write the outputs
    python3 -I tools/pages/build.py --check   write nothing; fail if an output is not what the source builds

The source is src/en-overlay/pages/space.toml, in GraceUI's page format. Its outputs:

  - src/en-overlay/pages/pages.json: the protocol's `space_pages` (the space, its name, the protocol minor its
    components need, its categories, pages, topics and commands);
  - src/en-overlay/pages/settings.json: the protocol's `settings_description` (its schema number, the hash GraceUI's
    format gives it, the first 16 hex digits of the SHA-256 of its settings' canonical JSON, and every setting with
    `synonyms` and `locked` filled in);
  - src/en-overlay/src/space_data.cpp: both, compact, as the string views eldennet.dll hands to register_pages.

The same JSON is what grace-dev reads from a space folder (GraceUI's §26): CTest assembles one for each fixture state
under tests/pages/ with these two files and the state's topics.json. The checks here are only those the conversion needs
(the fields each part may have); GraceUI's own lint (its tools/pages/build.py --lint, from the pinned GraceUI) checks
the rest in CTest. Standard library only; it reads nothing but its source.
"""
import argparse
import hashlib
import json
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
SOURCE = ROOT / "src" / "en-overlay" / "pages" / "space.toml"
PAGES_JSON = ROOT / "src" / "en-overlay" / "pages" / "pages.json"
SETTINGS_JSON = ROOT / "src" / "en-overlay" / "pages" / "settings.json"
SPACE_CPP = ROOT / "src" / "en-overlay" / "src" / "space_data.cpp"

PROTOCOL_MINOR = 1  # the components these pages draw are protocol 1.1's (GraceUI D172)
SPACE_FIELDS = ("id", "name", "settings_schema", "commands")
PAGE_FIELDS = ("id", "category", "name", "description", "help", "related", "increment", "tag", "actions", "tabs",
               "sections")
SETTING_FIELDS = ("key", "type", "default", "min", "max", "step", "unit", "choices", "third", "label", "help", "synonyms",
                  "home", "effect", "availability", "locked")
DELIMITER = ")space\""


class SourceError(Exception):
    pass


def only(where, table, fields):
    unknown = sorted(set(table) - set(fields))
    if unknown:
        raise SourceError(f"{where} has fields the format does not know: {', '.join(unknown)}")


def documents(text):
    source = tomllib.loads(text)
    only("the source", source, ("space", "topic", "category", "setting", "page"))
    space = source.get("space")
    if not isinstance(space, dict) or space.get("id") != "eldennet":
        raise SourceError("the source has no [space] with the id eldennet")
    only("[space]", space, SPACE_FIELDS)
    pages = []
    for page in source.get("page", []):
        only(f"page {page.get('id')}", page, PAGE_FIELDS)
        pages.append({k: page[k] for k in PAGE_FIELDS if k in page})
    space_pages = {
        "space": space["id"],
        "name": space["name"],
        "minor": PROTOCOL_MINOR,
        "categories": source.get("category", []),
        "pages": pages,
        "topics": source.get("topic", []),
        "commands": space.get("commands", []),
    }
    settings = []
    for entry in source.get("setting", []):
        only(f"setting {entry.get('key')}", entry, SETTING_FIELDS)
        one = dict(entry)
        one.setdefault("synonyms", [])
        one.setdefault("locked", False)
        settings.append({k: one[k] for k in SETTING_FIELDS if k in one})
    canonical = json.dumps(settings, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    description = {
        "schema": {"number": space.get("settings_schema", 1),
                   "hash": hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:16]},
        "settings": settings,
    }
    return space_pages, description


def pretty(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def space_cpp(space_pages, description):
    pages, settings = compact(space_pages), compact(description)
    if DELIMITER in pages or DELIMITER in settings:
        raise SourceError("the space's text holds the raw string's delimiter")
    return "\n".join([
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/pages/build.py from src/en-overlay/pages/space.toml: do not edit (PAGES §2; GraceUI D160).",
        "// EldenNet's page data and settings description, as the protocol's JSON, for register_pages (space.hpp).",
        '#include "en/overlay/space.hpp"',
        "",
        "namespace en::overlay {",
        "",
        "namespace {",
        "",
        f'constexpr std::string_view kPages = R"space({pages}){DELIMITER[1:]};',
        f'constexpr std::string_view kSettings = R"space({settings}){DELIMITER[1:]};',
        "",
        "}  // namespace",
        "",
        "std::string_view space_pages() noexcept { return kPages; }",
        "std::string_view settings_description() noexcept { return kSettings; }",
        "",
        "}  // namespace en::overlay",
        "",
    ])


def run(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if an output is not what the source builds")
    args = parser.parse_args(argv)
    try:
        space_pages, description = documents(SOURCE.read_text(encoding="utf-8"))
        outputs = {PAGES_JSON: pretty(space_pages), SETTINGS_JSON: pretty(description),
                   SPACE_CPP: space_cpp(space_pages, description)}
    except (SourceError, tomllib.TOMLDecodeError, KeyError, TypeError, OSError) as error:
        print(f"pages: {error}", file=sys.stderr)
        return 1
    if args.check:
        stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"pages: {path.relative_to(ROOT).as_posix()} is not what the source builds: run "
                  "python3 -I tools/pages/build.py", file=sys.stderr)
        if not stale:
            print("pages: ok (eldennet: %d pages, %d settings)" % (len(space_pages["pages"]),
                                                                    len(description["settings"])))
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    print("pages: wrote " + ", ".join(p.relative_to(ROOT).as_posix() for p in outputs))
    return 0


if __name__ == "__main__":
    sys.exit(run(sys.argv[1:]))

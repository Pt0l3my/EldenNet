std::string error_id(ErrorCode e) {
  const int n = static_cast<int>(e);
  return std::string("E") + (n < 10 ? "0" : "") + std::to_string(n);
}

std::string error_text(ErrorCode e, std::string_view s, std::uint32_t code) {
  const std::string str(s);
  const std::string num = std::to_string(code);
  switch (e) {
    case ErrorCode::E01:
      return "ELDEN RING was not found. Pick eldenring.exe, or start the launcher with --game \"<folder>\".";
    case ErrorCode::E02:
      return "Steam is not running. Start Steam, then run the EldenNet launcher again.";
    case ErrorCode::E03:
      return "ELDEN RING is already running. Close it, then start it again from this launcher.";
    case ErrorCode::E04:
      return "Easy Anti-Cheat is running (start_protected_game.exe). Close the game, then start it from this "
             "launcher.";
    case ErrorCode::E05:
      return "This game build (" + str +
             ") is not supported by this EldenNet version yet. Launch anyway? EldenNet will stay inactive until an "
             "update arrives.";
    case ErrorCode::E06:
      return "The launcher could not write steam_appid.txt into the game folder (" + str +
             "). Move the game to a folder you can write to, or see the install guide.";
    case ErrorCode::E07:
      return "Your save could not be backed up (" + str + "). Continue without a backup?";
    case ErrorCode::E08:
      return "eldennet.dll was not found next to the launcher (or at the --dll path).";
    case ErrorCode::E09:
      return "The game could not be started: " + str + " (code " + num + ").";
    case ErrorCode::E10:
      return "EldenNet could not be loaded into the game: the " + str + " step failed (code " + num +
             "). The game was closed again. Antivirus software sometimes blocks this step; see the install guide. "
             "Start the game without EldenNet instead?";
    case ErrorCode::E11:
      return "This launcher must run inside the game's Proton prefix. See the Proton notes in the install guide.";
  }
  return {};
}

std::string error_action(ErrorCode e) {
  switch (e) {
    case ErrorCode::E01:
      return "Open eldenring.exe…";
    case ErrorCode::E05:
      return "Launch anyway (EldenNet stays inactive)";
    case ErrorCode::E07:
      return "Continue without a backup";
    case ErrorCode::E10:
      return "Start without EldenNet";
    default:
      return {};
  }
}

